"""Разбор фраз о делах по расписанию: «каждое утро в 9 присылай курс доллара в Телеграм», «по пятницам в 18 собирай,
что я сделал за неделю», «каждый день в 8 делай утреннюю сводку», а также «сводка на сегодня» — сразу, без расписания.
Дело — напоминание особого вида (kind="job"): в срок ассистент не звонит, а сам выполняет поручение с инструментами
и присылает итог в Telegram/Max или говорит голосом.

Дату и повтор разбирает when.parse; здесь — только распознавание фразы. Сохранение и выполнение — в engine_music.py
(_job_cmd, _run_job), вызов инструментом — в engine_tools.py. Проверки — tests/jobs_test.py."""
import re

from when import parse as parse_when

VERBS = (r"присылай(?:те)?|присылать|отправляй(?:те)?|скидывай|кидай|пиши\s+мне|сообщай|рассказывай|говори|собирай|"
         r"делай|составляй|проверяй|узнавай|ищи|смотри|готовь|подводи|подсказывай|показывай|напоминай\s+мне\s+про\s+курс")
REPEAT = (r"\b(?:кажд\w+|ежедневно|еженедельно|ежечасно|периодически|регулярно|время\s+от\s+времени|в\s+течение\s+дня|"
          r"по\s+(?:утрам|вечерам|будням|выходным|понедельникам|вторникам|средам|четвергам|пятницам|субботам|воскресеньям|дням)|"
          r"раз\s+в)\b")
# «периодически проверяй почту» без интервала — каждый час (№137, 20.10: было напоминание человеку каждые 2 часа)
VAGUE = r"\b(?:ежечасно|периодически|регулярно|время\s+от\s+времени|в\s+течение\s+дня)\b"
BRIEF = r"утренн\w+\s+сводк\w*|сводк\w*\s+(?:на\s+)?(?:день|утро)|брифинг|утренн\w+\s+брифинг"
NOW_BRIEF = re.compile(r"^(?:(?:сделай|дай|расскажи|покажи)\s+)?(?:мне\s+)?(?:утренн\w+\s+сводк\w*|сводк\w*\s+на\s+(?:сегодня|день)|"
                       r"что\s+у\s+меня\s+(?:на\s+)?сегодня|какие\s+(?:у\s+меня\s+)?планы\s+на\s+сегодня|что\s+сегодня\s+по\s+плану)$")


def parse(text):
    """-> {"op": "job", "at", "repeat", "task", "deliver", "brief"} | {"op": "brief_now"} | None.

    deliver: "telegram" | "max" | "voice". Фраза без слова о повторе («каждый…», «по утрам…») или без глагола-поручения
    (кроме сводки) — не дело: None, её разбирают дальше как обычную команду или напоминание."""
    t = re.sub(r"[«»\"“”!?.]", " ", (text or "").lower().replace("ё", "е"))
    t = " ".join(t.split())
    if not t:
        return None
    if NOW_BRIEF.match(t):
        return {"op": "brief_now"}
    if not re.search(REPEAT, t):
        return None
    brief = bool(re.search(BRIEF, t))
    if not brief and not re.search(rf"\b(?:{VERBS})\b", t):
        return None
    # «…что завтра», «…за сегодня» после глагола — часть поручения, не дата: прячем от when.parse и потом возвращаем
    m = re.search(rf"\b(?:{VERBS})\b", t)
    keep = []
    if m:
        def hide(x):
            keep.append(x.group(0))
            return f"qq{len(keep) - 1}qq"
        # и «если придёт важное» — условие самого поручения, не повода «решать модели» (№137)
        t = t[:m.end()] + re.sub(r"\b(?:завтра|сегодня|вчера|послезавтра|если|ежели|иначе)\b", hide, t[m.end():])
    if re.search(VAGUE, t):
        t = re.sub(VAGUE, " ", t)
        if not re.search(r"\bкажд\w+\s+(?:\d+\s+)?(?:час|минут|полчаса)", t):
            t = "каждый час " + t
        t = " ".join(t.split())
    r = parse_when("напоминай " + t)
    # «по утрам», «каждый вечер» без часа when.parse повтором не считает — читаем как «каждый день в 9» / «в 20»
    if (not r or not r.get("repeat")) and re.search(r"по\s+утрам|кажд\w+\s+утр", t):
        r = parse_when("напоминай каждый день в 9 " + re.sub(r"по\s+утрам|кажд\w+\s+утр\w*", " ", t))
    if (not r or not r.get("repeat")) and re.search(r"по\s+вечерам|кажд\w+\s+вечер", t):
        r = parse_when("напоминай каждый день в 20 " + re.sub(r"по\s+вечерам|кажд\w+\s+вечер\w*", " ", t))
    if not r or not r.get("repeat"):
        return None
    task = re.sub(r"qq(\d+)qq", lambda x: keep[int(x.group(1))], r["text"] or "", flags=re.I)
    deliver = "max" if re.search(r"(?:в|на)\s+(?:макс\w*|max)\b", t) else (
        "telegram" if re.search(r"телеграм|телегу|телеге|\btg\b|в\s+телефон|сообщением", t) else "voice")
    task = re.sub(r"\s*(?:мне\s+)?(?:в|на)\s+(?:телеграм\w*|телегу|телеге|tg|телефон|макс\w*|max)\b", "", task, flags=re.I)
    task = re.sub(r"\s*сообщением\b", "", task, flags=re.I)
    task = " ".join(task.split()).strip(" ,.-") or ("Утренняя сводка" if brief else "")
    if not task:
        return None
    return {"op": "job", "at": r["at"], "repeat": r["repeat"], "task": task[0].upper() + task[1:], "deliver": deliver,
            "brief": brief}
