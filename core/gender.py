"""Род речи ассистента. Быстрые ответы без модели («Выключил музыку.», «Положил в сейф…», «Нажал «играть/пауза»») написаны
в мужском роде — у Лиры, Эвы и других героинь они переводятся в женский (for_persona). Меняются только слова из _FORMS
и только там, где говорит сам ассистент: в начале предложения или после двоеточия и тире (подлежащее «я» опущено), после
«я», «уже», «сейчас», «хорошо,», «готово,», «ладно,» и т. п., в том числе с «не» перед словом (_LEAD).
Третье лицо («станция не ответила», «заряд закончился», «сервер ответил») не трогаем.
Новые быстрые ответы пишем в мужском роде; новый глагол о себе — добавить в _VERBS. Для модели — prompt_rule(), а если
модель всё же сбилась («Рад слышать!» у Эвы) — её ответ тоже проходит for_persona (engine_answer._run_turn: голос и текст)."""
import re

# мужской род → женский: неправильные формы и прилагательные о себе; правильные глаголы — в _VERBS (+ «а»)
_FORMS = {
    "нашёл": "нашла", "нашел": "нашла", "перевёл": "перевела", "перевел": "перевела", "смог": "смогла", "помог": "помогла",
    "готов": "готова", "рад": "рада", "уверен": "уверена", "занят": "занята", "должен": "должна", "свободен": "свободна",
    "остановился": "остановилась", "ошибся": "ошиблась", "справился": "справилась", "разобрался": "разобралась",
    "освободился": "освободилась", "постарался": "постаралась", "вернулся": "вернулась",
}
_VERBS = """включил выключил добавил записал запустил нажал начал остановил открыл закрыл отменил передал показал положил понял
поставил приглушил расшифровал сделал скачал удалил узнал услышал вспомнил сохранил отправил переключил создал проверил
запомнил прочитал разобрал распознал решил сказал написал дописал ответил позвал получил принял подключил отключил убрал
вернул выполнил переслал посмотрел поискал искал подобрал нажимал сбросил очистил обновил установил настроил перенёс
отметил собрал подготовил посчитал записывал отложил поменял изменил увеличил уменьшил убавил прибавил продолжил
перезапустил приостановил возобновил выставил снял купил заказал загрузил выгрузил почистил""".split()
for _v in _VERBS:
    _FORMS.setdefault(_v, _v.replace("ё", "е") + "а" if not _v.endswith("ёс") else _v)
_FORMS["перенёс"] = "перенесла"              # на -ёс простое «+ а» не работает
# Только целые слова: по краям не буква и не дефис; длинные формы — первыми в перечне
_WORD = re.compile(r"(?<![\w-])(" + "|".join(sorted(map(re.escape, _FORMS), key=len, reverse=True)) + r")(?![\w-])", re.I)
_LEAD = re.compile(r"(?:^|[.!?…:—–]\s*|\b[Яя]\s+|\b[Яя]\s+уже\s+|\bуже\s+|\b[Сс]ейчас\s+|"
                   r"\b[Яя]\s+[^.!?…]{0,30}?\s(?:и|а|но)\s+|"           # «я на месте и готов», «я посмотрел и понял»
                   r"\b[Яя]\s+(?:очень|так|тоже|просто|правда|всегда|бы|сам|уже\s+не)\s+|"   # «я очень рад», «я тоже готов»
                   r"(?:^|[.!?…,]\s*)(?:очень|так|тоже|просто|правда|искренне|ужасно|страшно)\s+|"   # «Отлично, очень рад»
                   r"(?:хорошо|готово|ладно|ок|окей|да|так|сейчас|секунду|итак|отлично|прекрасно|здорово|супер|класс|"
                   r"замечательно|чудесно|конечно|ага|ну|ой|о|понятно|ясно|спасибо|привет|здравствуй(?:те)?),\s*)(?:не\s+)?$", re.I)


def _case(src, dst):
    return dst[:1].upper() + dst[1:] if src[:1].isupper() else dst


def feminine(text):
    """Мужской род ассистента → женский (только там, где говорит он сам; что перед словом — смотрим на 40 знаков
    назад). Заглавная буква сохраняется."""
    if not text:
        return text
    out, last = [], 0
    for m in _WORD.finditer(text):
        before = text[max(0, m.start() - 40):m.start()]
        if not _LEAD.search(before):
            continue
        out.append(text[last:m.start()])
        out.append(_case(m.group(1), _FORMS[m.group(1).lower()]))
        last = m.end()
    out.append(text[last:])
    return "".join(out)


def for_persona(text, gender):
    return feminine(text) if gender == "female" else text


def prompt_rule(gender):
    """Правило рода для системной подсказки модели (personas.system_prompt); род не указан — "".
    Женскому роду правило жёстче: модели часто сбиваются на мужской, особенно повторяя результаты инструментов."""
    if gender == "female":
        return ("Ты — женского рода. О себе говори только в женском роде: «я сделала», «поняла», «включила», «нашла», "
                "«рада», «готова», «не смогла». Никогда о себе не говори «сделал», «понял», «включил». Если в результатах "
                "инструментов или в репликах коллег написано в мужском роде — это не про тебя: сама говори в женском.")
    if gender == "male":
        return "О себе говори в мужском роде: «я сделал», «понял», «рад», «готов»."
    return ""
