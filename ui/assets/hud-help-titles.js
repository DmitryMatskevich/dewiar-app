  function enhance(el){
    const extra=notes[el.id];if(!extra)return;
    const fixed={'b-upd':'Обновления','b-pad':'Блокнот'};
    const current=fixed[el.id]||el.getAttribute('title')||el.dataset.tip||el.getAttribute('aria-label')||el.textContent.trim();
    const base=current.includes(extra)?current.slice(0,current.indexOf(extra)).trim():current;
    const text=(base?base+'\n\n':'')+extra;
    if(el.title!==text)el.title=text;
  }
